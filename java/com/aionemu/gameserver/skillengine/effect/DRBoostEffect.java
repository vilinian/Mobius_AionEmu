package com.aionemu.gameserver.skillengine.effect;

import javax.xml.bind.annotation.XmlAccessType;
import javax.xml.bind.annotation.XmlAccessorType;
import javax.xml.bind.annotation.XmlType;

import com.aionemu.gameserver.skillengine.model.Effect;

/**
 * This class handles the Damage Reduction boost effect.<br>
 * It provides logic for increasing a character's defense capabilities.<br>
 * It extends {@link BuffEffect} to manage its behavior within the skill engine.
 * @author Rolandas
 */
@XmlAccessorType(XmlAccessType.FIELD)
@XmlType(name = "DRBoostEffect")
public class DRBoostEffect extends BuffEffect
{
	/**
	 * Calculates the attributes for a specific {@code Effect}.<br>
	 * This method updates the {@code effect} to include an AP boost.<br>
	 * It also links this instance as a success effect.
	 * @param effect The {@code Effect} object to be updated.
	 */
	@Override
	public void calculate(Effect effect)
	{
		effect.setDrBoost(true);
		effect.addSucessEffect(this);
	}
}
