package com.aionemu.gameserver.dao;

import com.aionemu.commons.database.dao.DAO;
import com.aionemu.gameserver.model.gameobjects.player.Player;
import com.aionemu.gameserver.model.gameobjects.player.equipmentsetting.EquipmentSetting;

/**
 * This class provides data access operations for {@link EquipmentSetting} objects.<br>
 * It handles the persistence of player-specific equipment configurations in the database.
 * @author Falke_34
 */
public abstract class PlayerEquipmentSettingDAO implements DAO
{
	public abstract void loadEquipmentSetting(Player player);
	
	public abstract void insertEquipmentSetting(Player player, EquipmentSetting equipmentSetting);
	
	/**
	 * Returns the name of the current class.<br>
	 * This is useful for identifying the {@code DAO} type in logs or configurations.
	 * @return The full name of the class as a {@code String}.
	 */
	@Override
	public String getClassName()
	{
		return PlayerEquipmentSettingDAO.class.getName();
	}
}
