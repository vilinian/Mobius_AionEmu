package com.aionemu.gameserver.model.templates.item.grind;

import javax.xml.bind.annotation.XmlAttribute;
import javax.xml.bind.annotation.XmlType;

/**
 * Represents a reward granted to players for completing specific grinding tasks.<br>
 * This class defines the items or rewards associated with {@code Grind} activities.
 */
@XmlType(name = "GrindReward")
public class GrindReward
{
	@XmlAttribute(name = "item_id")
	public int itemId;
	
	/**
	 * Retrieves the unique identifier for this wardrobe item.<br>
	 * This value corresponds to the {@code itemId} assigned during object creation.
	 * @return The unique {@code int} ID of the item.
	 */
	public int getItemId()
	{
		return itemId;
	}
}
