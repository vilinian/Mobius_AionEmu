package com.aionemu.gameserver.dao;

import com.aionemu.commons.database.dao.DAO;
import com.aionemu.gameserver.model.gameobjects.player.Player;
import com.aionemu.gameserver.model.gameobjects.player.title.Title;
import com.aionemu.gameserver.model.gameobjects.player.title.TitleList;

/**
 * This class provides data access operations for managing a {@link TitleList}.<br>
 * It handles the persistence of player titles in the database.<br>
 * It serves as a base for retrieving and saving title collections for a {@link Player}.
 * @author xavier
 */
public abstract class PlayerTitleListDAO implements DAO
{
	/**
	 * Returns the name of the current class.<br>
	 * This is useful for identifying the {@code DAO} type in logs or configurations.
	 * @return The full name of the class as a {@code String}.
	 */
	@Override
	public String getClassName()
	{
		return PlayerTitleListDAO.class.getName();
	}
	
	public abstract TitleList loadTitleList(int playerId);
	
	public abstract boolean storeTitles(Player player, Title entry);
	
	public abstract boolean removeTitle(int playerId, int titleId);
}
